// ─── Route handler ────────────────────────────────────────────────────────────

export async function POST(req: NextRequest) {
  try {
    const answers = await req.json() as Answers

    const token    = generateBriefToken()
    const briefUrl = `${BASE_URL}/brief/${token}`

    const naming = await generateNamingDirections(answers)
    const project: ProjectState = naming
      ? { ...DEFAULT_PROJECT, status: 'generated', brandCharacter: naming.brandCharacter, territories: naming.territories }
      : DEFAULT_PROJECT

    let emailStatus: 'sent' | 'failed' = 'failed'
    try {
      const resend = new Resend(process.env.RESEND_API_KEY)
      const { data, error } = await resend.emails.send({
        from:    FROM_EMAIL,
        to:      TO_EMAIL,
        subject: `Brand Naming — ${answers.business_name || 'New submission'} · ${answers.client_name || 'Unknown'} · ${answers.industry || ''}`,
        html:    buildEmail(answers, briefUrl, naming),
        text:    buildClaudeDoc(answers, briefUrl, naming),
      })
      if (error) {
        console.error('Resend error:', JSON.stringify(error))
      } else {
        emailStatus = 'sent'
        console.log('Email sent:', data?.id)
      }
    } catch (emailErr) {
      // Email is a best-effort notification — its failure doesn't lose the
      // submission, which is why the Blob write below is unconditional.
      console.error('Email send failed:', emailErr)
    }

    // Blob write is the transaction of record. If it throws, the outer catch
    // returns ok:false so the client can tell the user their submission
    // wasn't saved, instead of silently showing "Thank you" over a lost
    // response.
    await put(`submissions/${token}.json`, JSON.stringify({
      token,
      submittedAt: new Date().toISOString(),
      briefUrl,
      emailStatus,
      answers,
      project,
    }, null, 2), { access: 'public', addRandomSuffix: false })

    return NextResponse.json({ ok: true, briefUrl })
  } catch (err) {
    console.error('Submit error:', err)
    return NextResponse.json({ ok: false }, { status: 500 })
  }
}
