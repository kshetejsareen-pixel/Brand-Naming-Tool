const TO_EMAIL   = 'info@kshetejsareen.com'
const FROM_EMAIL = process.env.FROM_EMAIL ?? 'onboarding@resend.dev'
const BASE_URL   = process.env.NEXT_PUBLIC_BASE_URL ?? 'https://brand-naming-tool.vercel.app'

// ─── Brief token ──────────────────────────────────────────────────────────────
// A random, unguessable ID rather than a base64 dump of the raw answers — the
// old scheme put a client's full unencrypted diagnostic in the URL bar with no
// expiry and no auth. The token now just addresses a (non-public) Blob record.

function generateBriefToken(): string {
  return randomUUID().replace(/-/g, '')
}

// ─── Report sections — the one place answers become human-readable text ──────
// Both the Claude-ready doc and the internal email render from this, so their
// substantive content can never drift apart from each other or from the
// question definitions in src/lib/schema.ts.

interface ReportField { key: string; value: string }
interface ReportSection { num: string; label: string; fields: ReportField[] }

function buildReportSections(a: Answers): ReportSection[] {
  return getReportModules().map((mod) => {
    // Module 03 is a derived profile (phonosemantic score + explicit cultural
    // register), not a raw per-question dump — the individual word-pair
    // choices are noise once they're summarized.
    if (mod.num === '03') {
      const profile = phonosemanticProfile(a)
      return {
        num: mod.num,
        label: mod.label,
        fields: [
          { key: 'Sonic profile', value: `${profile.direction} (${profile.score}/${profile.total} soft)` },
          { key: 'Market scope', value: formatAnswer('market_scope', a.market_scope) },
          { key: 'Cultural register', value: formatAnswer('cultural_register', a.cultural_register) },
        ],
      }
    }
    return {
      num: mod.num,
      label: mod.label,
      fields: mod.ids.map((id) => ({
        key: SCREENS_BY_ID[id].briefLabel,
        value: formatAnswer(id, a[id]),
      })),
    }
  })
}

// ─── Claude-ready Phase 2 document (plain text, uploaded to Claude) ───────────
// If in-house generation succeeded, this shows the actual results. If it
// didn't (no API key configured, or the call failed), it falls back to the
// original manual-copy-paste instructions so the studio can still generate
// names by hand — generation is an enhancement, not a hard dependency.

